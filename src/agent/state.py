"""
Global State Definition for the Enterprise Lakehouse AI Agent.
Tracks the end-to-end lifecycle across gate guardrails, generation, AST security, reflection, execution, and synthesis.
"""

from typing import TypedDict, List, Dict, Any, Optional


class LakehouseAgentState(TypedDict):
    # ==========================================
    # 1. INPUT CONTEXT (Grounding)
    # ==========================================
    question: str                    # Original user prompt / analytical business question
    target_tables: List[str]         # Candidate tables (e.g. ['orders', 'order_items'])
    schema_context: str              # Schema context reflected from Trino information_schema
    max_attempts: int                # Maximum allowed reflection retries (e.g. 3)

    # ==========================================
    # 2. PERIMETER 1: GATE GUARDRAIL (Node 0)
    # ==========================================
    is_gate_approved: bool           # True if passes input guardrail, False if injection/destructive/gibberish
    gate_rejection_reason: Optional[str] # Explanation if blocked at the gate

    # ==========================================
    # 3. STAGE 1: SQL GENERATION (Node 1)
    # ==========================================
    sql_query: str                   # Candidate SQL query generated by Node 1
    generation_reasoning: str        # Step-by-step logic detailing table selections, joins, aggregations
    attempt_count: int               # Current iteration count (starts at 1)

    # ==========================================
    # 4. PERIMETER 2: DETERMINISTIC AST SECURITY GATE
    # ==========================================
    is_security_approved: bool       # True if passes sqlglot AST checks, False if rejected
    security_violation: Optional[str]# Exact reason if blocked (e.g., "Prohibited operation: DROP")

    # ==========================================
    # 5. LLM-AS-A-JUDGE / REFLECTION (Node 2B)
    # ==========================================
    is_intent_aligned: bool          # True if query satisfies user's semantic demand
    judge_reasoning: Optional[str]   # Judge critique of SQL logic against prompt intent
    judge_feedback: Optional[str]    # Actionable suggestions fed back to Node 1 on retry

    # ==========================================
    # 6. MCP QUERY EXECUTION (Trino Engine)
    # ==========================================
    execution_success: bool          # True if Trino ran successfully, False if runtime error
    query_result: Optional[List[Dict[str, Any]]] # Tabular JSON rows returned from Lakehouse
    execution_error: Optional[str]   # Trino syntax/compiler error message (if any)

    # ==========================================
    # 7. STAGE 2: FINAL SYNTHESIS & AUDIT
    # ==========================================
    final_answer: str                # Natural language business answer OR security rejection notice
    status: str                      # Lifecycle status: "SUCCESS" | "SECURITY_BLOCKED" | "MAX_RETRIES_EXCEEDED"
